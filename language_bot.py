def get_progress_bar(current_xp: int, level: int) -> str:
    if level >= 30:
        return "👑 МАКСИМАЛЬНЫЙ УРОВЕНЬ"
    needed = xp_for_level(level)
    level_start_xp = total_xp_for_level(level)
    progress_xp = current_xp - level_start_xp
    filled = int((progress_xp / needed) * 10)
    bar = "█" * filled + "░" * (10 - filled)
    return f"[{bar}] {progress_xp}/{needed} XP"


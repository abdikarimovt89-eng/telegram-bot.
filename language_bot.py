def xp_for_level(level: int) -> int:
    """XP нужно для перехода на следующий уровень"""
    return level * 100

def total_xp_for_level(level: int) -> int:
    """Суммарный XP для достижения этого уровня"""
    return sum(xp_for_level(i) for i in range(1, level))

def get_level_from_xp(xp: int) -> int:
    level = 1
    while level < 30 and xp >= total_xp_for_level(level + 1):
        level += 1
    return level


# Для остальных языков используем упрощённую систему (повторяем вопросы по уровням)
def build_simple_lang(name, base_questions):
    """Создаёт 30 уровней из базового набора вопросов"""
    questions_pool = base_questions
    levels = {}
    for lvl in range(1, 31):
        # Более сложные уровни = больше перемешивания и другой порядок
        pool = questions_pool[:]
        random.shuffle(pool)
        levels[lvl] = pool
    return {"name": name, "questions": levels}


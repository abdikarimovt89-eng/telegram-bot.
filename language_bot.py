async def hint_chosen(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()

    parts = query.data.split("_", 1)
    q_index = int(parts[1])
    current_q_index = context.user_data.get("q_index", 0)

    if q_index != current_q_index:
        await query.answer("Этот вопрос уже отвечен!", show_alert=True)
        return QUIZ

    coins = context.user_data.get("coins", 0)
    if coins < HINT_COST:
        await query.answer(f"Недостаточно монет! Нужно {HINT_COST}💰, у тебя {coins}💰", show_alert=True)
        return QUIZ

    # Списываем монеты
    context.user_data["coins"] = coins - HINT_COST
    context.user_data["hint_used"] = True

    # Убираем 2 неверных варианта
    questions = context.user_data.get("questions", [])
    question = questions[q_index]
    correct = question["answer"]
    wrong_options = [o for o in question["options"] if o != correct]
    random.shuffle(wrong_options)
    removed = wrong_options[:2]
    remaining_options = [o for o in question["options"] if o not in removed]
    random.shuffle(remaining_options)

    new_coins = context.user_data["coins"]
    xp = context.user_data.get("xp", 0)
    level = get_level_from_xp(xp)
    progress = get_progress_bar(xp, level)

    text = (
        f"💡 Подсказка использована! (-{HINT_COST}💰)\n"
        f"💰 Монет осталось: {new_coins}\n\n"
        f"❓ Вопрос {q_index + 1} | Ур. {level} | 💰 {new_coins}\n"
        f"{progress}\n\n"
        f"*{question['q']}*"
    )
    keyboard = get_options_keyboard(remaining_options, q_index, hint_used=True, coins=new_coins)
    await query.edit_message_text(text, parse_mode="Markdown", reply_markup=keyboard)
    return QUIZ

# ─── Запуск ───────────────────────────────────────────────────────────────────

def main():
    app = Application.builder().token(BOT_TOKEN).build()

    conv = ConversationHandler(
        entry_points=[
            CommandHandler("start", start),
            CommandHandler("quiz", quiz_command),
            CommandHandler("restart", restart_command),
        ],
        states={
            CHOOSING_LANG: [CallbackQueryHandler(language_chosen, pattern="^lang_")],
            QUIZ: [CallbackQueryHandler(answer_chosen, pattern="^ans_")],
        },
        fallbacks=[
            CommandHandler("restart", restart_command),
            CommandHandler("start", start),
        ],
    )

    app.add_handler(conv)
    app.add_handler(CommandHandler("level", level_command))
    app.add_handler(CommandHandler("wallet", wallet_command))
    app.add_handler(CommandHandler("help", help_command))
    app.add_handler(CallbackQueryHandler(hint_chosen, pattern="^hint_"))

    print("🤖 Бот запущен!")
    app.run_polling()

if __name__ == "__main__":
    main()

async def send_question(update: Update, context: ContextTypes.DEFAULT_TYPE, is_callback=False):
    q_index = context.user_data["q_index"]
    questions = context.user_data["questions"]

    if q_index >= len(questions):
        await finish_quiz(update, context)
        return

    question = questions[q_index]
    options = question["options"][:]
    random.shuffle(options)

    xp = context.user_data.get("xp", 0)
    coins = context.user_data.get("coins", 0)
    level = get_level_from_xp(xp)
    progress = get_progress_bar(xp, level)
    hint_used = context.user_data.get("hint_used", False)

    text = (
        f"❓ Вопрос {q_index + 1}/{len(questions)} | Ур. {level} | 💰 {coins}\n"
        f"{progress}\n\n"
        f"*{question['q']}*"
    )
    keyboard = get_options_keyboard(options, q_index, hint_used=hint_used, coins=coins)
    chat_id = update.effective_chat.id
    await context.bot.send_message(
        chat_id=chat_id,
        text=text,
        parse_mode="Markdown",
        reply_markup=keyboard
    )

async def answer_chosen(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()

    parts = query.data.split("_", 2)
    if len(parts) < 3:
        return QUIZ

    q_index = int(parts[1])
    chosen = parts[2]
    current_q_index = context.user_data.get("q_index", 0)

    if q_index != current_q_index:
        await query.answer("Этот вопрос уже отвечен!", show_alert=True)
        return QUIZ

    questions = context.user_data.get("questions", [])
    question = questions[q_index]
    correct = question["answer"]

    xp = context.user_data.get("xp", 0)
    level_before = get_level_from_xp(xp)

    context.user_data["session_total"] = context.user_data.get("session_total", 0) + 1

    if chosen == correct:
        reward = xp_reward(level_before, True)
        context.user_data["xp"] = xp + reward
        context.user_data["coins"] = context.user_data.get("coins", 0) + COINS_PER_CORRECT
        context.user_data["session_correct"] = context.user_data.get("session_correct", 0) + 1
        context.user_data["hint_used"] = False  # сброс подсказки для следующего вопроса

        new_xp = context.user_data["xp"]
        new_coins = context.user_data["coins"]
        level_after = get_level_from_xp(new_xp)

        if level_after > level_before:
            result_text = (
                f"✅ Правильно! *{correct}*\n"
                f"⚡ +{reward} XP | +{COINS_PER_CORRECT}💰\n"
                f"💰 Монет всего: {new_coins}\n\n"
                f"🎊 *НОВЫЙ УРОВЕНЬ!*\n"
                f"🏅 Уровень {level_after}/30 — {get_level_title(level_after)}"
            )
        else:
            progress = get_progress_bar(new_xp, level_after)
            result_text = (
                f"✅ Правильно! *{correct}*\n"
                f"⚡ +{reward} XP | +{COINS_PER_CORRECT}💰\n"
                f"💰 Монет всего: {new_coins}\n"
                f"{progress}"
            )
    else:
        context.user_data["hint_used"] = False  # сброс подсказки для следующего вопроса
        result_text = f"❌ Неверно!\nПравильный ответ: *{correct}*\n⚡ +0 XP | +0💰"

    await query.edit_message_text(result_text, parse_mode="Markdown")
    context.user_data["q_index"] += 1
    await send_question(update, context, is_callback=True)
    return QUIZ

async def finish_quiz(update: Update, context: ContextTypes.DEFAULT_TYPE):
    session_correct = context.user_data.get("session_correct", 0)
    session_total = context.user_data.get("session_total", 0)
    xp = context.user_data.get("xp", 0)
    level = get_level_from_xp(xp)
    title = get_level_title(level)
    progress = get_progress_bar(xp, level)
    lang_key = context.user_data.get("current_lang", "")
    lang_name = get_lang_name(lang_key)

    percent = round(session_correct / session_total * 100) if session_total > 0 else 0

    if percent == 100:
        emoji, comment = "🏆", "Все ответы верны! Великолепно!"
    elif percent >= 80:
        emoji, comment = "🌟", "Отличный результат!"
    elif percent >= 60:
        emoji, comment = "👍", "Хороший результат! Продолжай!"
    else:
        emoji, comment = "📚", "Не сдавайся, практика — ключ к успеху!"

    coins = context.user_data.get("coins", 0)
    earned_coins = session_correct * COINS_PER_CORRECT
    text = (
        f"{emoji} Викторина завершена!\n\n"
        f"🌍 Язык: {lang_name}\n"
        f"✅ Правильно: {session_correct}/{session_total} ({percent}%)\n"
        f"{comment}\n\n"
        f"💰 Заработано монет: +{earned_coins}\n"
        f"💰 Монет всего: {coins}\n\n"
        f"🏅 Уровень: {level}/30 — {title}\n"
        f"⚡ XP: {xp}\n"
        f"{progress}\n\n"
        f"Напиши /quiz для следующего раунда!"
    )
    chat_id = update.effective_chat.id
    await context.bot.send_message(chat_id=chat_id, text=text)


def get_questions_for_level(lang_key: str, level: int) -> list:
    """Получить вопросы для конкретного языка и уровня"""
    if lang_key == "english":
        pool = QUIZ_DATA["english"]["questions"].get(level, [])
        if not pool:
            # Если вопросов для уровня нет — берём из ближайшего
            all_levels = sorted(QUIZ_DATA["english"]["questions"].keys())
            closest = min(all_levels, key=lambda x: abs(x - level))
            pool = QUIZ_DATA["english"]["questions"][closest][:]
        else:
            pool = pool[:]
    else:
        lang_data = SIMPLE_LANGS.get(lang_key, {})
        base = lang_data.get("base", [])
        pool = base[:]
        random.shuffle(pool)

    random.shuffle(pool)
    return pool[:5]  # 5 вопросов на уровень

def get_lang_name(lang_key: str) -> str:
    if lang_key == "english":
        return QUIZ_DATA["english"]["name"]
    return SIMPLE_LANGS.get(lang_key, {}).get("name", lang_key)

